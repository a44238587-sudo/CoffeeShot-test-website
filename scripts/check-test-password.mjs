import assert from 'node:assert/strict';
import { isAllowedCloudflareBuild } from './project-command.mjs';
import { onTestRequest, TEST_PASSWORD } from './test-password.js';
if (!isAllowedCloudflareBuild() || process.env.CLOUDFLARE_BUILD_MODE !== 'full') throw new Error('Password access checks require the remote Full build.');
const call = (path, init = {}) => onTestRequest({ request: new Request(`https://test.example${path}`, init), next: async () => new Response('protected content') });
assert.equal((await call('/', { headers: { Accept: 'text/html' } })).status, 303);
assert.equal((await call('/assets/app.js')).status, 401);
assert.equal((await call('/api/private', { method: 'POST' })).status, 401);
assert.equal((await call('/test-access/')).status, 200);
const login = password => call('/api/test-access', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ password }) });
assert.equal((await login('incorrect')).status, 401);
assert.equal((await login(TEST_PASSWORD.toUpperCase())).status, 401);
const accepted = await login(TEST_PASSWORD);
assert.equal(accepted.status, 200);
assert.equal((await accepted.json()).admitted, true);
const cookie = accepted.headers.get('set-cookie').split(';')[0];
assert.equal(await (await call('/assets/app.js', { headers: { Cookie: cookie } })).text(), 'protected content');
assert.equal(await (await call('/api/private', { method: 'POST', headers: { Cookie: cookie } })).text(), 'protected content');
assert.equal((await (await call('/api/test-access', { headers: { Cookie: cookie } })).json()).admitted, true);
assert.match((await call('/api/test-access', { method: 'DELETE', headers: { Cookie: cookie } })).headers.get('set-cookie'), /Max-Age=0/);
console.log('Password access checks passed: admission, assets, API, case sensitivity and logout.');
